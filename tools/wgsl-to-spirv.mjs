#!/usr/bin/env node
/**
 * Generate C++ headers from a WGSL shader file.
 *
 *   --input <path>        path to source .wgsl
 *   --out-dir <dir>       directory for generated .h files
 *   --name <ident>        C++ identifier prefix (e.g. basicLineShader)
 *   --emit text|spirv|both  which artifacts to emit (default: both)
 *   --naga <path>         path to naga executable; defaults to $NAGA or `naga` on PATH
 *
 * Outputs (inside out-dir):
 *   <name>.wgsl.h    : `inline constexpr const char <name>_wgsl[] = R"WGSL(...)WGSL";`
 *   <name>.spirv.h   : `inline constexpr uint32_t <name>_spirv[N] = { ... };`
 *
 * Both headers are wrapped in `namespace sculptcore::shaders::generated {}`.
 *
 * SPIR-V emission shells out to the `naga` CLI; the resulting module contains
 * all entry points from the .wgsl (typically `vs_main` and `fs_main`).
 * Vulkan picks the entry point per pipeline stage via VkPipelineShaderStageCreateInfo.pName.
 */
import fs from 'fs'
import Path from 'path'
import child_process from 'child_process'
import os from 'os'

function parseArgs(argv) {
  const out = {emit: 'both'}
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i]
    if (a === '--input') out.input = argv[++i]
    else if (a === '--out-dir') out.outDir = argv[++i]
    else if (a === '--name') out.name = argv[++i]
    else if (a === '--emit') out.emit = argv[++i]
    else if (a === '--naga') out.naga = argv[++i]
    else {
      process.stderr.write(`wgsl-to-spirv: unknown argument ${a}\n`)
      process.exit(2)
    }
  }
  for (const k of ['input', 'outDir', 'name']) {
    if (!out[k]) {
      process.stderr.write(`wgsl-to-spirv: --${k === 'outDir' ? 'out-dir' : k} is required\n`)
      process.exit(2)
    }
  }
  if (!['text', 'spirv', 'both'].includes(out.emit)) {
    process.stderr.write(`wgsl-to-spirv: --emit must be text|spirv|both, got ${out.emit}\n`)
    process.exit(2)
  }
  return out
}

function ensureDir(p) {
  if (!fs.existsSync(p)) fs.mkdirSync(p, {recursive: true})
}

function emitText({input, outDir, name}) {
  const src = fs.readFileSync(input, 'utf8')
  // Pick a raw-string delimiter not present in the source.
  let delim = 'WGSL'
  while (src.includes(`)${delim}"`)) delim += 'X'
  const headerPath = Path.join(outDir, `${name}.wgsl.h`)
  const body =
    `// Generated by tools/wgsl-to-spirv.mjs from ${Path.basename(input)}. Do not edit.\n` +
    `#pragma once\n` +
    `namespace sculptcore::shaders::generated {\n` +
    `inline constexpr const char ${name}_wgsl[] = R"${delim}(${src})${delim}";\n` +
    `} // namespace sculptcore::shaders::generated\n`
  fs.writeFileSync(headerPath, body)
}

function resolveNaga(explicit) {
  const candidates = []
  if (explicit) candidates.push(explicit)
  if (process.env.NAGA) candidates.push(process.env.NAGA)
  candidates.push('naga')
  for (const c of candidates) {
    try {
      child_process.execFileSync(c, ['--version'], {stdio: 'pipe'})
      return c
    } catch {
      /* keep looking */
    }
  }
  return null
}

function emitSpirv({input, outDir, name, naga}) {
  const tool = resolveNaga(naga)
  if (!tool) {
    process.stderr.write(
      `wgsl-to-spirv: cannot find 'naga' CLI on PATH or via $NAGA.\n` +
        `  Install with: node make.mjs install-tools\n`
    )
    process.exit(3)
  }

  const tmp = fs.mkdtempSync(Path.join(os.tmpdir(), 'wgsl2spv-'))
  const spvPath = Path.join(tmp, `${name}.spv`)
  try {
    const res = child_process.spawnSync(tool, [input, spvPath], {stdio: 'pipe'})
    if (res.status !== 0) {
      process.stderr.write(`naga failed (exit ${res.status}) for ${input}:\n`)
      if (res.stdout?.length) process.stderr.write(res.stdout.toString())
      if (res.stderr?.length) process.stderr.write(res.stderr.toString())
      process.exit(res.status || 1)
    }
    const buf = fs.readFileSync(spvPath)
    if (buf.length % 4 !== 0) {
      process.stderr.write(`wgsl-to-spirv: SPIR-V file size ${buf.length} not a multiple of 4\n`)
      process.exit(4)
    }
    const words = new Uint32Array(buf.buffer, buf.byteOffset, buf.length / 4)
    let body =
      `// Generated by tools/wgsl-to-spirv.mjs from ${Path.basename(input)}. Do not edit.\n` +
      `#pragma once\n` +
      `#include <cstdint>\n` +
      `namespace sculptcore::shaders::generated {\n` +
      `inline constexpr uint32_t ${name}_spirv[${words.length}] = {\n`
    const lines = []
    for (let i = 0; i < words.length; i += 8) {
      const chunk = []
      for (let j = i; j < Math.min(i + 8, words.length); j++) {
        chunk.push('0x' + words[j].toString(16).padStart(8, '0') + 'u')
      }
      lines.push('  ' + chunk.join(', ') + ',')
    }
    body += lines.join('\n') + '\n};\n'
    body += `} // namespace sculptcore::shaders::generated\n`
    fs.writeFileSync(Path.join(outDir, `${name}.spirv.h`), body)
  } finally {
    try {
      fs.rmSync(tmp, {recursive: true, force: true})
    } catch {
      /* ignore */
    }
  }
}

const args = parseArgs(process.argv.slice(2))
ensureDir(args.outDir)
if (args.emit === 'text' || args.emit === 'both') emitText(args)
if (args.emit === 'spirv' || args.emit === 'both') emitSpirv(args)
